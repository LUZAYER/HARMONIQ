#!/usr/bin/env python3
"""
Generate results/numbers.tex with LaTeX macros from empirical results files.

Integrity Guarantee:
Zero hand-typed numbers in LaTeX. Every number is an auto-generated macro
derived directly from results/stats_table.csv, results/ablation_results.csv,
results/thresholds.json, results/split_summary.csv, and results/efficiency_results.csv.
"""

import os
import sys
import json
import argparse
import pandas as pd
import numpy as np


DIGIT_MAP = {
    '0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three', '4': 'Four',
    '5': 'Five', '6': 'Six', '7': 'Seven', '8': 'Eight', '9': 'Nine'
}


def clean_macro_name(name: str) -> str:
    """Ensures macro names contain strictly alphabetic characters [A-Za-z]."""
    # Replace digits with words
    converted = ""
    for char in name:
        if char in DIGIT_MAP:
            converted += DIGIT_MAP[char]
        elif char.isalpha():
            converted += char
        elif char in ['_', '-', ' ']:
            converted += '_'

    # CamelCase parts
    clean_parts = [part.capitalize() for part in converted.split('_') if part]
    return "".join(clean_parts)


def format_macro(name: str, val, precision: int = 3) -> str:
    """Formats a LaTeX macro string safely."""
    macro_name = clean_macro_name(name)
    if isinstance(val, (float, np.floating)):
        formatted_val = f"{val:.{precision}f}"
    else:
        formatted_val = str(val)
    return f"\\newcommand{{\\{macro_name}}}{{{formatted_val}}}\n"


def generate_numbers_tex(
    stats_csv: str = "results/stats_table.csv",
    ablation_csv: str = "results/ablation_results.csv",
    thresholds_json: str = "results/thresholds.json",
    split_summary_csv: str = "results/split_summary.csv",
    efficiency_csv: str = "results/efficiency_results.csv",
    output_tex: str = "results/numbers.tex"
):
    macros = []
    macros.append("% Auto-generated by experiments/make_numbers.py - DO NOT EDIT MANUALLY\n")

    # 1. Dataset Partition Numbers
    if os.path.exists(split_summary_csv):
        splits_df = pd.read_csv(split_summary_csv)
        total_resp = splits_df[splits_df["Dataset"] == "Pooled Total"]["N_Responses"].sum()
        macros.append(format_macro("DatasetTotalResponses", total_resp))

        for _, row in splits_df.iterrows():
            ds = row["Dataset"].replace(" ", "").replace("-", "")
            sp = row["Split"].capitalize()
            macros.append(format_macro(f"N{ds}{sp}Responses", row["N_Responses"]))
            macros.append(format_macro(f"N{ds}{sp}Claims", row["N_Claims"]))
            macros.append(format_macro(f"Prev{ds}{sp}", f"{row['Prevalence']*100:.1f}"))

    # 2. Main System Performance Metrics
    if os.path.exists(stats_csv):
        stats_df = pd.read_csv(stats_csv)
        for _, row in stats_df.iterrows():
            sys_id = row["System"].replace(" ", "").replace("-", "_").replace("(", "").replace(")", "")
            macros.append(format_macro(f"AUC{sys_id}", row["AUC"]))
            if "AUC_CI_Low" in row and "AUC_CI_High" in row:
                macros.append(format_macro(f"AUCLow{sys_id}", row["AUC_CI_Low"]))
                macros.append(format_macro(f"AUCHigh{sys_id}", row["AUC_CI_High"]))
            macros.append(format_macro(f"BalAcc{sys_id}", row["Bal_Acc"]))
            macros.append(format_macro(f"FPR{sys_id}", f"{row['FPR']*100:.1f}"))
            macros.append(format_macro(f"FNR{sys_id}", f"{row['FNR']*100:.1f}"))
            macros.append(format_macro(f"ECE{sys_id}", row["ECE"]))
            macros.append(format_macro(f"Brier{sys_id}", row["Brier"]))

    # 3. Dev-Tuned Operating Thresholds & Aggregation Parameters
    if os.path.exists(thresholds_json):
        with open(thresholds_json, "r", encoding="utf-8") as f:
            th = json.load(f)
        macros.append(format_macro("TauStar", th.get("tau_star", 0.50)))
        macros.append(format_macro("TauFPRFive", th.get("tau_fpr5", 0.90)))
        macros.append(format_macro("TauRecNinety", th.get("tau_rec90", 0.10)))
        macros.append(format_macro("AlphaHCS", th.get("alpha", 0.70), precision=2))
        macros.append(format_macro("BetaHCS", th.get("beta", 0.05), precision=3))
        macros.append(format_macro("DevECE", th.get("ece_fixed", 0.0)))
        macros.append(format_macro("DevBrier", th.get("brier_score", 0.0)))

    # 4. Ablation Deltas
    if os.path.exists(ablation_csv):
        abl_df = pd.read_csv(ablation_csv)
        for _, row in abl_df.iterrows():
            cfg_name = row["Configuration"]
            macros.append(format_macro(f"AblAUC{cfg_name}", row["AUC"]))
            if "Delta_AUC" in row:
                delta_str = f"{row['Delta_AUC']:+.3f}"
                macro_delta_name = clean_macro_name(f"DeltaAUC{cfg_name}")
                macros.append(f"\\newcommand{{\\{macro_delta_name}}}{{{delta_str}}}\n")

    # 5. Efficiency & Latency Numbers
    if os.path.exists(efficiency_csv):
        eff_df = pd.read_csv(efficiency_csv)
        for _, row in eff_df.iterrows():
            comp_id = row["Component"].replace(" ", "").replace("-", "_").replace("(", "").replace(")", "")
            macros.append(format_macro(f"LatencyMean{comp_id}", row["Mean_ms"], precision=1))
            macros.append(format_macro(f"LatencyPninetyfive{comp_id}", row["p95_ms"], precision=1))

    os.makedirs(os.path.dirname(output_tex), exist_ok=True)
    with open(output_tex, "w", encoding="utf-8") as f:
        f.writelines(macros)

    print(f"✓ Exported {len(macros)} LaTeX macros to {output_tex}")


if __name__ == '__main__':
    generate_numbers_tex()
